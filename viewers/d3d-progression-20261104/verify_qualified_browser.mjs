import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {nearestHeatSegment,formatHeatQ} from './dist/heat-probe.mjs';
const read=p=>JSON.parse(readFileSync(new URL(p,import.meta.url),'utf8'));
const hash=p=>createHash('sha256').update(readFileSync(new URL(p,import.meta.url))).digest('hex');
const observed=read('./qualified-browser-observations.json');
const index=read('./dist/qualified-finals.json'),data=read('./dist/data.json'),stages=read('./dist/stage-profiles.json');
assert.equal(index.data_sha256,hash('./dist/data.json'));
assert.equal(observed.console.length,0);
assert.equal(observed.observations.length,4);
const checked=[];
for(const o of observed.observations){
  assert.equal(o.probeHidden,false);
  const radius=Number(o.case.match(/RMIN (\d+) MM/)[1]);
  const e=index.entries.find(e=>e.series===`campaign-OMP-${radius}`);
  assert.ok(e);
  const series=data.series.find(s=>s.id===e.series);
  const stage=series.stages[Number(o.stage)-1];
  assert.equal(stage.id,e.final.id);
  const isFinal=o.mode==='final',row=isFinal?e.final:stage;
  const rel=isFinal?row.profile:stages.cases[row.id].profile;
  const p=read('./dist/'+rel);
  const rz=[...o.position.matchAll(/(?:R|Z) (-?[\d.]+)/g)].map(m=>Number(m[1]));
  assert.equal(rz.length,2);
  const hit=nearestHeatSegment(rz,p.segments,2e-5);
  assert.ok(hit);
  assert.equal(o.q,`q = ${formatHeatQ(hit.q)} MW/m²`);
  assert.equal(o.peak,row.peak.toFixed(4));
  assert.ok(o.resolution.startsWith(isFinal?'1280 경로':'320 경로'));
  assert.equal(o.title,isFinal?'추가 정밀검증 결과':`개선 단계 ${o.stage}`);
  checked.push({...o,recomputed_q:hit.q,coordinate_to_cell_distance_m:hit.distance,profile:rel,profile_sha256:hash('./dist/'+rel)});
}
assert.equal(checked.filter(o=>o.surface==='3D').length,1);
assert.equal(checked.filter(o=>o.surface==='RZ').length,3);
const r100=observed.regressions.find(r=>r.case==='OMP / RMIN 100 MM');
assert.equal(r100.finalDisabled,true);assert.equal(r100.title,'D3D 기준 형상');assert.equal(r100.peak,'2.7308');
const imp=observed.regressions.find(r=>r.case==='IMP / RMIN 20 MM');
assert.equal(imp.finalDisabled,false);assert.equal(imp.peak,'2.3752');assert.equal(imp.status,'현재 정밀검증 통과');
const baseline=observed.regressions.find(r=>r.display==='baseline');
assert.ok(baseline.heat.startsWith('기준 형상 · 1280 경로'));
const result={passed:true,url:observed.url,checked,regressions:observed.regressions,console_errors:0};
writeFileSync(new URL('./qualified-browser-verification.json',import.meta.url),JSON.stringify(result,null,2));
console.log({passed:true,actual_browser_q_values_verified:checked.length,regressions:observed.regressions.length,console_errors:0});
